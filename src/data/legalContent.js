export function getLegalContent(docId = null) {
  try {
    const raw = typeof window !== 'undefined' ? localStorage.getItem(LEGAL_STORAGE_KEY) : null;
    let stored = {};
    if (raw) {
      stored = JSON.parse(raw);
    }
    const merged = { ...defaultLegalContent, ...stored };
    return docId ? merged[docId] || defaultLegalContent[docId] : merged;
  } catch (e) {
    console.warn('Failed to load legal content overrides from storage, falling back to defaults:', e);
    return docId ? defaultLegalContent[docId] : defaultLegalContent;
  }
}

/**
 * פונקציית עזר לשמירת עריכות של מסמך משפטי ישירות מפאנל הניהול.
 */
export function saveLegalDocument(docId, updatedDoc) {
  try {
    if (typeof window === 'undefined') return false;
    const current = getLegalContent();
    current[docId] = {
      ...current[docId],
      ...updatedDoc,
      lastUpdated: new Date().toLocaleDateString('he-IL', { year: 'numeric', month: 'long' })
    };
    localStorage.setItem(LEGAL_STORAGE_KEY, JSON.stringify(current));
    return true;
  } catch (e) {
    console.error('Failed to save legal document to storage:', e);
    return false;
  }
}

/**
 * איפוס מסמך משפטי לברירת המחדל המקורית
 */
export function resetLegalDocumentToDefault(docId) {
  try {
    if (typeof window === 'undefined') return false;
    const raw = localStorage.getItem(LEGAL_STORAGE_KEY);
    if (!raw) return true;
    const stored = JSON.parse(raw);
    delete stored[docId];
    localStorage.setItem(LEGAL_STORAGE_KEY, JSON.stringify(stored));
    return true;
  } catch (e) {
    console.error('Failed to reset legal document:', e);
    return false;
  }
}

